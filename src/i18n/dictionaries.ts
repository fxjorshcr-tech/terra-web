const dicts: Record<Locale, Dict> = { es, en, fr, de };

export function getDict(lang: string): Dict {
  return dicts[(locales as readonly string[]).includes(lang) ? (lang as Locale) : defaultLocale];
}

export function esLocale(lang: string): lang is Locale {
  return (locales as readonly string[]).includes(lang);
}

// Los títulos siguen el patrón "Tipo en Lugar"; se traducen de forma
// programática. Las descripciones largas permanecen en español hasta que se
// agreguen traducciones propias por propiedad.
export function tituloPropiedad(p: Propiedad, lang: Locale, d: Dict): string {
  if (lang === "es") return p.titulo;
  const m = p.titulo.match(/^(Casa|Lote|Finca) en (.+)$/);
  if (!m) return p.titulo;
  return `${d.tipos[m[1] as Propiedad["tipo"]]} ${d.comun.en} ${m[2]}`;
}

// Rellena plantillas tipo "Hola {nombre}" con valores.
export function tpl(plantilla: string, vars: Record<string, string>): string {
  return plantilla.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}
